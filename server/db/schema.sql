CREATE TABLE IF NOT EXISTS profile (
  id INT UNSIGNED NOT NULL PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  tagline VARCHAR(255) NOT NULL,
  intro TEXT NOT NULL,
  about TEXT NOT NULL,
  email VARCHAR(254) NOT NULL,
  phone VARCHAR(40) NOT NULL,
  location VARCHAR(120) NOT NULL DEFAULT '',
  github_url VARCHAR(500) NOT NULL,
  linkedin_url VARCHAR(500) NOT NULL,
  leetcode_url VARCHAR(500) NOT NULL,
  resume_path VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS skill_categories (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  sort_order INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS skills (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  category_id INT UNSIGNED NOT NULL,
  name VARCHAR(100) NOT NULL,
  sort_order INT NOT NULL,
  CONSTRAINT fk_skills_category FOREIGN KEY (category_id)
    REFERENCES skill_categories(id) ON DELETE CASCADE,
  UNIQUE KEY uq_skills_category_name (category_id, name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS projects (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(180) NOT NULL,
  badge VARCHAR(80) NOT NULL,
  description TEXT NOT NULL,
  github_url VARCHAR(500) NOT NULL,
  live_url VARCHAR(500) NULL,
  sort_order INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS project_tech (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  project_id INT UNSIGNED NOT NULL,
  tech VARCHAR(100) NOT NULL,
  sort_order INT NOT NULL,
  CONSTRAINT fk_project_tech_project FOREIGN KEY (project_id)
    REFERENCES projects(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS project_highlights (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  project_id INT UNSIGNED NOT NULL,
  text TEXT NOT NULL,
  sort_order INT NOT NULL,
  CONSTRAINT fk_project_highlights_project FOREIGN KEY (project_id)
    REFERENCES projects(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS education (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  institution VARCHAR(180) NOT NULL,
  degree VARCHAR(180) NOT NULL,
  score VARCHAR(80) NOT NULL,
  location VARCHAR(120) NOT NULL,
  start_label VARCHAR(40) NOT NULL,
  end_label VARCHAR(40) NOT NULL,
  sort_order INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS achievements (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(160) NOT NULL,
  description TEXT NOT NULL,
  sort_order INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
